/**
 * Record builder and I/O utilities.
 *
 * Standardizes the JSON record format used across all scripts.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

export const STUDIO_OWNER = 'mcp-tool-shop';
export const STUDIO_LICENCE = 'CC-BY-4.0';
export const AI_ASSISTED_DISCLOSURE_NOTE =
  'AI-assisted generation on Apache-2.0 base models; curated and owned by mcp-tool-shop under CC-BY-4.0.';

/**
 * Build the default rights and ownership block for a record (G5, §2.3).
 */
export function buildDefaultRights(overrides = {}) {
  return {
    owner: STUDIO_OWNER,
    licence: STUDIO_LICENCE,
    ai_assisted_disclosure: true,
    disclosure_note: AI_ASSISTED_DISCLOSURE_NOTE,
    ...(overrides || {}),
  };
}

/**
 * Build a base provenance record (generated by txt2img scripts).
 * Supports positional `(id, assetPath, imageData, provenance, extra)` and
 * object-style `({ id, assetPath, imageData, dimensions, provenance, canon, owner, licence, rights })`.
 */
export function buildBaseRecord(idOrOpts, assetPath, imageData, provenance, extra = {}) {
  let id = idOrOpts;
  let resolvedAssetPath = assetPath;
  let resolvedImage = imageData;
  let resolvedProvenance = provenance;
  let resolvedExtra = extra || {};

  if (idOrOpts && typeof idOrOpts === 'object' && !Array.isArray(idOrOpts)) {
    id = idOrOpts.id;
    resolvedAssetPath = idOrOpts.assetPath ?? idOrOpts.asset_path;
    resolvedImage = idOrOpts.imageData ?? idOrOpts.dimensions ?? idOrOpts.image ?? {};
    resolvedProvenance = idOrOpts.provenance ?? null;
    resolvedExtra = idOrOpts;
  }

  const img = resolvedImage || {};
  const rights = buildDefaultRights(resolvedExtra.rights);
  const owner = resolvedExtra.owner ?? rights.owner;
  const licence = resolvedExtra.licence ?? rights.licence;

  return {
    id,
    schema_version: '2.0.0',
    created_at: new Date().toISOString(),
    owner,
    licence,
    rights: {
      ...rights,
      owner,
      licence,
    },
    asset_path: resolvedAssetPath,
    image: {
      format: img.format || 'png',
      width: img.width || 1024,
      height: img.height || 1024,
      bytes: img.bytes || 0,
    },
    provenance: resolvedProvenance,
    judgment: null,
    canon: resolvedExtra.canon ?? null,
    iteration: null,
  };
}

/**
 * Build an identity record (extends base with identity + lineage blocks).
 */
export function buildIdentityRecord(baseRecord, identity, lineage) {
  return {
    ...baseRecord,
    identity,
    lineage,
  };
}

/**
 * Load a record by asset ID from a records directory.
 * @param {string} recordsDir — absolute path to records/
 * @param {string} assetId — record filename (without .json)
 * @returns {Promise<Object|null>}
 */
export async function loadRecord(recordsDir, assetId) {
  const path = join(recordsDir, `${assetId}.json`);
  try {
    const raw = await readFile(path, 'utf-8');
    return JSON.parse(raw);
  } catch (err) {
    if (err.code === 'ENOENT') return null;
    throw new Error(`Failed to load record ${assetId}: ${err.message}`);
  }
}

/**
 * Save a record to disk.
 * @param {string} recordsDir — absolute path to records/
 * @param {string} assetId — record filename (without .json)
 * @param {Object} record — the record object
 */
export async function saveRecord(recordsDir, assetId, record) {
  const path = join(recordsDir, `${assetId}.json`);
  await writeFile(path, JSON.stringify(record, null, 2) + '\n');
}
